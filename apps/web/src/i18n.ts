export type Key = keyof (typeof dict)["ru"];
export const t = (lang: Lang, k: Key): string => dict[lang][k];

export type Currency = "UZS" | "USD";
/** amount — в минимальных единицах (тийин / центы). */
export function formatMoney(amount: number, cur: Currency, lang: Lang): string {
  const major = amount / 100;
  return new Intl.NumberFormat(localeOf(lang), {
    style: "currency", currency: cur, maximumFractionDigits: cur === "UZS" ? 0 : 2,
  }).format(major);
}

/** Сумма в минимальных единицах из ввода в основных (12.5 → 1250). */
export const toMinor = (v: string): number => Math.round(Number(v.replace(",", ".")) * 100);
